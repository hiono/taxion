// Command gencompletion derives offline completion from the actual CLI help.
package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

func generate() ([]byte, error) {
	file, err := parser.ParseFile(token.NewFileSet(), "main.go", nil, 0)
	if err != nil {
		return nil, err
	}
	commands := map[string]map[string]bool{"": {"--store": true, "--help": true, "--version": true}, "completion": {"bash": true}}
	ast.Inspect(file, func(node ast.Node) bool {
		value, ok := node.(*ast.ValueSpec)
		if !ok || len(value.Names) != 1 || value.Names[0].Name != "usage" {
			return true
		}
		text, _ := strconv.Unquote(value.Values[0].(*ast.BasicLit).Value)
		for _, line := range strings.Split(text, "\n") {
			if !strings.HasPrefix(line, "  ") {
				continue
			}
			words := strings.Fields(line)
			if len(words) < 2 || words[0] == "taxion" || strings.HasPrefix(words[1], "<") ||
				!regexp.MustCompile(`^[a-z][a-z-]*$`).MatchString(words[0]) {
				continue
			}
			name := words[0]
			if regexp.MustCompile(`^[a-z][a-z-]*$`).MatchString(words[1]) {
				name += " " + words[1]
			}
			commands[name] = map[string]bool{}
		}
		return false
	})
	for _, name := range []string{"git hook install", "git hook status", "git hook remove",
		"memory conflict add", "memory conflict list", "memory conflict resolve", "help"} {
		commands[name] = map[string]bool{}
	}
	for _, name := range []string{"workflow plan", "workflow start", "workflow terminate"} {
		commands[name]["--file"] = true
		commands[name]["--help"] = true
	}
	// Build once, then query help with no HOME, config, Git environment or tools.
	// No-flag actions are excluded because they may perform work instead of help.
	noFlags := map[string]bool{"completion": true, "completion bash": true, "gen-token": true, "help": true,
		"provenance verify": true,
		"memory checks":     true, "records show": true, "task graph": true,
		"git hook": true, "git hook status": true, "git hook remove": true,
		"memory conflict": true, "workflow plan": true, "workflow start": true, "workflow terminate": true}
	directory, err := os.MkdirTemp("", "taxion-completion-*")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(directory)
	binary := filepath.Join(directory, "taxion")
	if output, err := exec.Command("go", "build", "-o", binary, ".").CombinedOutput(); err != nil {
		return nil, fmt.Errorf("build completion source: %w: %s", err, output)
	}
	optionPattern := regexp.MustCompile(`(?m)^  -([a-z][a-z0-9-]*)(?:[ \n])`)
	for name := range commands {
		if name == "" || noFlags[name] {
			continue
		}
		args := append(strings.Fields(name), "--help")
		command := exec.Command(binary, args...)
		command.Dir = directory
		command.Env = []string{"HOME=" + directory, "XDG_CONFIG_HOME=" + directory, "PATH="}
		output, err := command.CombinedOutput()
		var exit *exec.ExitError
		if err != nil && !errors.As(err, &exit) {
			return nil, err
		}
		if !bytes.Contains(output, []byte("Usage of ")) {
			return nil, fmt.Errorf("command %s has no flag help; classify it explicitly before generating completion: %s", name, output)
		}
		commands[name]["--help"] = true
		for _, match := range optionPattern.FindAllSubmatch(output, -1) {
			commands[name]["--"+string(match[1])] = true
		}
	}
	for name := range commands {
		parts := strings.Fields(name)
		for i, part := range parts {
			parent := strings.Join(parts[:i], " ")
			if commands[parent] == nil {
				commands[parent] = map[string]bool{}
			}
			commands[parent][part] = true
		}
	}
	var keys []string
	for name := range commands {
		keys = append(keys, name)
	}
	sort.Strings(keys)
	var out strings.Builder
	out.WriteString("# Generated by go generate ./cmd/taxion; do not edit.\n_taxion_complete() {\n    local cur path='' word skip=0 options=0 i\n    COMPREPLY=()\n    cur=${COMP_WORDS[COMP_CWORD]}\n    for ((i=1; i<COMP_CWORD; i++)); do\n        word=${COMP_WORDS[i]}\n        if ((skip)); then skip=0; continue; fi\n        if [[ $word == --store ]]; then skip=1; continue; fi\n        if [[ $word == -* ]]; then options=1; break; fi\n        path=${path:+$path }$word\n    done\n    local candidates=''\n    case \"$path\" in\n")
	for _, key := range keys {
		var candidates []string
		for candidate := range commands[key] {
			candidates = append(candidates, candidate)
		}
		sort.Strings(candidates)
		fmt.Fprintf(&out, "        '%s') candidates='%s' ;;\n", key, strings.Join(candidates, " "))
	}
	out.WriteString("    esac\n    local candidate\n    while IFS= read -r candidate; do\n        if ((options)) && [[ $candidate != -* ]]; then continue; fi\n        [[ -n $candidate ]] && COMPREPLY+=(\"$candidate\")\n    done < <(compgen -W \"$candidates\" -- \"$cur\")\n    return 0\n}\ncomplete -F _taxion_complete taxion\n")
	return []byte(out.String()), nil
}

func main() {
	data, err := generate()
	if err == nil && len(os.Args) == 2 && os.Args[1] == "--check" {
		var existing []byte
		existing, err = os.ReadFile("completion.bash")
		if err == nil && !bytes.Equal(data, existing) {
			err = fmt.Errorf("completion.bash is stale; run go generate ./cmd/taxion")
		}
	} else if err == nil {
		err = os.WriteFile("completion.bash", data, 0o644)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
