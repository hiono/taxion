func CaptureSnapshot(dispatch core.GraphDispatch, result *core.DispatchResult) error {
	if result == nil || dispatch.Recipient != "CODER" ||
		dispatch.Instruction.OutputMode != core.OutputModeWorktreeTreeSnapshot {
		return fmt.Errorf("tree snapshot requires a snapshot-mode Coder result")
	}
	if result.DispatchID != dispatch.ID || result.TaskID != dispatch.TaskID ||
		result.Recipient != dispatch.Recipient || result.Repository != dispatch.Repository ||
		result.StartedSHA != dispatch.ExpectedStartSHA() {
		return fmt.Errorf("tree snapshot result does not match its Coder Dispatch")
	}
	root, err := worktreeRoot(dispatch.Instruction.Worktree)
	if err != nil {
		return err
	}
	remote, err := git(root, "remote", "get-url", "origin")
	if err != nil {
		return fmt.Errorf("read snapshot worktree origin: %w", err)
	}
	if err := VerifyRepositoryRemote(dispatch, remote); err != nil {
		return fmt.Errorf("snapshot worktree origin does not match repository")
	}
	baseline, err := git(root, "rev-parse", dispatch.Instruction.BaselineSHA+"^{commit}")
	if err != nil || baseline != dispatch.Instruction.BaselineSHA {
		return fmt.Errorf("snapshot baseline is not the exact approved commit")
	}
	head, err := git(root, "rev-parse", "HEAD")
	if err != nil {
		return err
	}
	if head != dispatch.ExpectedStartSHA() || result.OutputSHA != head {
		return fmt.Errorf("snapshot mode requires unchanged execution-start commit %s", dispatch.ExpectedStartSHA())
	}
	branch, err := git(root, "symbolic-ref", "--quiet", "--short", "HEAD")
	if err != nil || branch != dispatch.Instruction.Branch {
		return fmt.Errorf("snapshot worktree branch does not match the Coder Dispatch")
	}
	tree, files, _, err := captureWorktreeTree(root, dispatch.Instruction.BaselineSHA, head)
	if err != nil {
		return err
	}
	if !sameFiles(files, result.ChangedFiles) {
		return fmt.Errorf("Git snapshot changed files %v do not match reported files %v", files, result.ChangedFiles)
	}
	if err := CheckChangedPaths(dispatch, files); err != nil {
		return err
	}
	if result.OutputTreeSHA != "" {
		return fmt.Errorf("output tree SHA is generated by the controller")
	}
	if err := pinSnapshot(root, dispatch.ID, tree); err != nil {
		return err
	}
	result.OutputTreeSHA = tree
	for index := range result.Validations {
		result.Validations[index].Worktree = root
		result.Validations[index].SHA = tree
	}
	return nil
}

func verifySnapshot(dispatch core.GraphDispatch, result *core.DispatchResult) error {
	if dispatch.Instruction.OutputMode != core.OutputModeWorktreeTreeSnapshot ||
		result.DispatchID != dispatch.ID || result.TaskID != dispatch.TaskID ||
		result.Recipient != dispatch.Recipient || result.Repository != dispatch.Repository ||
		result.Status != core.DispatchSucceeded || result.StartedSHA != dispatch.ExpectedStartSHA() ||
		!fullSHA(result.OutputSHA) || !fullSHA(result.OutputTreeSHA) ||
		!fullSHA(dispatch.Instruction.BaselineSHA) ||
		(dispatch.Instruction.TargetSHA != "" && !fullSHA(dispatch.Instruction.TargetSHA)) {
		return fmt.Errorf("snapshot verification result does not match a complete Dispatch identity")
	}
	if dispatch.Recipient == "REVIEWER" &&
		(!fullSHA(dispatch.Instruction.TargetTreeSHA) ||
			result.OutputTreeSHA != dispatch.Instruction.TargetTreeSHA) {
		return fmt.Errorf("Reviewer snapshot does not match the approved target tree")
	}
	root, err := worktreeRoot(dispatch.Instruction.Worktree)
	if err != nil {
		return err
	}
	remote, err := git(root, "remote", "get-url", "origin")
	if err != nil {
		return fmt.Errorf("read snapshot worktree origin: %w", err)
	}
	if err := VerifyRepositoryRemote(dispatch, remote); err != nil {
		return fmt.Errorf("snapshot worktree origin does not match repository")
	}
	baseline, err := git(root, "rev-parse", dispatch.Instruction.BaselineSHA+"^{commit}")
	if err != nil || baseline != dispatch.Instruction.BaselineSHA {
		return fmt.Errorf("snapshot baseline is not the exact approved commit")
	}
	head, err := git(root, "rev-parse", "HEAD")
	if err != nil {
		return err
	}
	if head != result.OutputSHA {
		return fmt.Errorf("snapshot worktree HEAD %s does not match reported commit %s", head, result.OutputSHA)
	}
	if dispatch.Recipient == "CODER" && head != dispatch.ExpectedStartSHA() {
		return fmt.Errorf("snapshot mode cannot create commits after execution start")
	}
	if dispatch.Recipient == "REVIEWER" &&
		(head != baseline || result.OutputSHA != baseline) {
		return fmt.Errorf("Reviewer must inspect the unchanged baseline commit")
	}
	branch, err := git(root, "symbolic-ref", "--quiet", "--short", "HEAD")
	if err != nil {
		var exit *exec.ExitError
		if dispatch.Recipient != "REVIEWER" || !errors.As(err, &exit) || exit.ExitCode() != 1 {
			return fmt.Errorf("read snapshot worktree branch: %w", err)
		}
		branch = "(detached)"
	}
	if branch != "(detached)" && branch != dispatch.Instruction.Branch {
		return fmt.Errorf("snapshot worktree branch %q does not match Dispatch branch %q", branch, dispatch.Instruction.Branch)
	}
	tree, files, clean, err := captureWorktreeTree(root, baseline, head)
	if err != nil {
		return err
	}
	if tree != result.OutputTreeSHA {
		return fmt.Errorf("snapshot worktree tree %s differs from reported tree %s", tree, result.OutputTreeSHA)
	}
	evidenceFiles := files
	if dispatch.Recipient == "CODER" {
		if !sameFiles(files, result.ChangedFiles) {
			return fmt.Errorf("Git snapshot changed files %v do not match reported files %v", files, result.ChangedFiles)
		}
		if err := CheckChangedPaths(dispatch, files); err != nil {
			return err
		}
	} else {
		targetFiles, err := changedFiles(root, baseline, dispatch.Instruction.TargetTreeSHA)
		if err != nil {
			return err
		}
		if !sameFiles(targetFiles, dispatch.Instruction.TargetChangedFiles) {
			return fmt.Errorf("Reviewer target paths differ from its issued tree snapshot")
		}
		coderContract := dispatch
		coderContract.Recipient = "CODER"
		if err := CheckChangedPaths(coderContract, targetFiles); err != nil {
			return fmt.Errorf("Reviewer target exceeds the authorized Coder scope: %w", err)
		}
		if len(result.ChangedFiles) != 0 || result.WorktreeChanged == nil || *result.WorktreeChanged {
			return fmt.Errorf("Reviewer changed the immutable tree snapshot")
		}
		evidenceFiles = []string{}
	}
	refDispatchID := dispatch.ID
	if dispatch.Recipient == "REVIEWER" {
		if dispatch.RelatedID == "" {
			return fmt.Errorf("Reviewer snapshot has no source Coder Dispatch")
		}
		refDispatchID = dispatch.RelatedID
	}
	if err := verifySnapshotRef(root, refDispatchID, result.OutputTreeSHA); err != nil {
		return err
	}
	for _, validation := range result.Validations {
		if validation.Worktree == "" || validation.SHA != tree {
			return fmt.Errorf("validation %q has incomplete or mismatched snapshot provenance", validation.Command)
		}
		validationRoot, err := worktreeRoot(validation.Worktree)
		if err != nil || validationRoot != root {
			return fmt.Errorf("validation %q provenance does not match the snapshot worktree", validation.Command)
		}
		validationHead, err := git(validationRoot, "rev-parse", "HEAD")
		if err != nil || validationHead != head {
			return fmt.Errorf("validation %q provenance does not match the snapshot baseline commit", validation.Command)
		}
	}
	parentLine, err := git(root, "rev-list", "--parents", "-n", "1", head)
	if err != nil {
		return err
	}
	parentFields := strings.Fields(parentLine)
	if len(parentFields) == 0 || parentFields[0] != head {
		return fmt.Errorf("read parents for snapshot baseline commit %s", head)
	}
	result.GitEvidence = &core.DispatchGitEvidence{
		Worktree: root, Repository: dispatch.Repository, Branch: branch,
		BaselineSHA: baseline, HeadSHA: head, ParentSHAs: parentFields[1:],
		ChangedFiles: evidenceFiles, TreeSHA: tree,
		SnapshotRef: snapshotRef(refDispatchID), SnapshotMatches: true,
		WorktreeClean: clean, VerifiedAt: time.Now().UTC(),
	}
	for i := range result.Validations {
		result.Validations[i].Worktree = root
	}
	return nil
}

func captureWorktreeTree(root, baseline, head string) (tree string, files []string, clean bool, err error) {
	index, err := os.CreateTemp("", "taxion-snapshot-index-*")
	if err != nil {
		return "", nil, false, fmt.Errorf("create snapshot Git index: %w", err)
	}
	indexPath := index.Name()
	if err := index.Close(); err != nil {
		removeErr := os.Remove(indexPath)
		if removeErr != nil {
			return "", nil, false, errors.Join(fmt.Errorf("close snapshot Git index: %w", err),
				fmt.Errorf("remove snapshot Git index: %w", removeErr))
		}
		return "", nil, false, fmt.Errorf("close snapshot Git index: %w", err)
	}
	if err := os.Remove(indexPath); err != nil {
		return "", nil, false, fmt.Errorf("initialize snapshot Git index: %w", err)
	}
	defer func() {
		if removeErr := os.Remove(indexPath); removeErr != nil && !errors.Is(removeErr, os.ErrNotExist) {
			err = errors.Join(err, fmt.Errorf("remove snapshot Git index: %w", removeErr))
		}
	}()
	if _, err := gitWithIndex(root, indexPath, "read-tree", head); err != nil {
		return "", nil, false, err
	}
	if _, err := gitWithIndex(root, indexPath, "add", "-A", "--", "."); err != nil {
		return "", nil, false, fmt.Errorf("snapshot worktree: %w", err)
	}
	tree, err = gitWithIndex(root, indexPath, "write-tree")
	if err != nil {
		return "", nil, false, fmt.Errorf("write snapshot Git tree: %w", err)
	}
	if !fullSHA(tree) {
		return "", nil, false, fmt.Errorf("snapshot Git tree is not a full SHA")
	}
	files, err = changedFiles(root, baseline, tree)
	if err != nil {
		return "", nil, false, err
	}
	status, err := git(root, "status", "--porcelain", "--untracked-files=all")
	if err != nil {
		return "", nil, false, err
	}
	return tree, files, status == "", nil
}

// CheckPortableWorktree refuses unrecorded edits instead of silently losing
// them during migration. Ignored files are not part of recorded Git artifacts.
func CheckPortableWorktree(root, head, tree string) error {
	actualHead, err := git(root, "rev-parse", "HEAD")
	if err != nil || actualHead != head {
		return fmt.Errorf("portable worktree HEAD differs from recorded evidence")
	}
	if tree == "" {
		tree, err = git(root, "rev-parse", head+"^{tree}")
		if err != nil {
			return err
		}
	}
	index, err := os.CreateTemp("", "taxion-portable-index-*")
	if err != nil {
		return err
	}
	path := index.Name()
	if err := index.Close(); err != nil {
		os.Remove(path)
		return err
	}
	if err := os.Remove(path); err != nil {
		return err
	}
	defer os.Remove(path)
	options := []string{"-c", "core.fsmonitor=false", "-c", "core.hooksPath=/dev/null", "-c", "core.untrackedCache=false"}
	if _, err := gitWithIndex(root, path, append(options, "read-tree", tree)...); err != nil {
		return err
	}
	if _, err := gitWithIndex(root, path, append(options, "diff", "--quiet", "--no-ext-diff", "--no-textconv")...); err != nil {
		return fmt.Errorf("portable worktree contains unrecorded changes; reconcile before snapshot")
	}
	extra, err := gitWithIndex(root, path, append(options, "ls-files", "--others", "--exclude-standard")...)
	if err != nil {
		return err
	}
	if extra != "" {
		return fmt.Errorf("portable worktree contains unrecorded files; reconcile before snapshot")
	}
	return nil
}

func ObserveSnapshotStart(dispatch core.GraphDispatch) (string, error) {
	if dispatch.Recipient == "REVIEWER" {
		changed := false
		result := &core.DispatchResult{
			DispatchID: dispatch.ID, TaskID: dispatch.TaskID, Recipient: dispatch.Recipient,
			Repository: dispatch.Repository, Status: core.DispatchSucceeded,
			StartedSHA: dispatch.ExpectedStartSHA(), OutputSHA: dispatch.ExpectedStartSHA(),
			OutputTreeSHA: dispatch.Instruction.TargetTreeSHA, ChangedFiles: []string{},
			WorktreeChanged: &changed,
		}
		if err := Verify(dispatch, result); err != nil {
			return "", fmt.Errorf("Reviewer snapshot start verification: %w", err)
		}
		return result.GitEvidence.HeadSHA, nil
	}
	if dispatch.Recipient != "CODER" {
		return "", fmt.Errorf("tree snapshot start requires a Coder or Reviewer Dispatch")
	}
	root, err := worktreeRoot(dispatch.Instruction.Worktree)
	if err != nil {
		return "", err
	}
	remote, err := git(root, "remote", "get-url", "origin")
	if err != nil {
		return "", fmt.Errorf("read snapshot worktree origin: %w", err)
	}
	if err := VerifyRepositoryRemote(dispatch, remote); err != nil {
		return "", fmt.Errorf("snapshot worktree origin does not match repository")
	}
	head, err := git(root, "rev-parse", "HEAD")
	if err != nil {
		return "", err
	}
	if head != dispatch.ExpectedStartSHA() {
		return "", fmt.Errorf("snapshot worktree HEAD %s does not match execution start %s", head, dispatch.ExpectedStartSHA())
	}
	branch, err := git(root, "symbolic-ref", "--quiet", "--short", "HEAD")
	if err != nil || branch != dispatch.Instruction.Branch {
		return "", fmt.Errorf("snapshot worktree branch does not match the Coder Dispatch")
	}
	tree, files, clean, err := captureWorktreeTree(root, dispatch.Instruction.BaselineSHA, head)
	if err != nil {
		return "", err
	}
	expectedTree := dispatch.Instruction.TargetTreeSHA
	if expectedTree == "" {
		expectedTree, err = git(root, "rev-parse", head+"^{tree}")
		if err != nil {
			return "", err
		}
		if !clean || len(files) != 0 {
			return "", fmt.Errorf("initial snapshot Coder worktree must be clean")
		}
	} else {
		if dispatch.RelatedID != "" {
			err = verifySnapshotRef(root, dispatch.RelatedID, expectedTree)
		} else {
			err = verifyRetainedSnapshot(root, expectedTree)
		}
		if err != nil {
			return "", fmt.Errorf("prior snapshot is unavailable: %w", err)
		}
		if !sameFiles(files, dispatch.Instruction.TargetChangedFiles) {
			return "", fmt.Errorf("snapshot continuation changed paths differ from the approved target")
		}
		if err := CheckChangedPaths(dispatch, files); err != nil {
			return "", err
		}
	}
	if tree != expectedTree {
		return "", fmt.Errorf("snapshot Coder worktree tree %s differs from approved start tree %s", tree, expectedTree)
	}
	return head, nil
}

func verifyRetainedSnapshot(root, tree string) error {
	refs, err := git(root, "for-each-ref", "--format=%(objectname)", "refs/taxion/snapshots")
	if err != nil {
		return err
	}
	for _, retained := range strings.Fields(refs) {
		if retained == tree {
			return nil
		}
	}
	return fmt.Errorf("no retained snapshot ref points to tree %s", tree)
}

func applyTreeSnapshot(source string, dispatch core.GraphDispatch) error {
	if dispatch.Instruction.OutputMode != core.OutputModeWorktreeTreeSnapshot ||
		!fullSHA(dispatch.Instruction.TargetTreeSHA) || dispatch.RelatedID == "" {
		return fmt.Errorf("Reviewer snapshot requires a source Dispatch and full target tree SHA")
	}
	if err := verifySnapshotRef(source, dispatch.RelatedID, dispatch.Instruction.TargetTreeSHA); err != nil {
		return err
	}
	targetFiles, err := changedFiles(source, dispatch.Instruction.BaselineSHA, dispatch.Instruction.TargetTreeSHA)
	if err != nil {
		return err
	}
	if !sameFiles(targetFiles, dispatch.Instruction.TargetChangedFiles) {
		return fmt.Errorf("Reviewer target paths differ from the approved Coder snapshot")
	}
	coderContract := dispatch
	coderContract.Recipient = "CODER"
	if err := CheckChangedPaths(coderContract, targetFiles); err != nil {
		return fmt.Errorf("Reviewer snapshot exceeds the Coder scope: %w", err)
	}
	command := exec.Command("git", "-C", source, "diff", "--no-ext-diff", "--no-textconv",
		"--no-renames", "--binary", dispatch.Instruction.BaselineSHA, dispatch.Instruction.TargetTreeSHA)
	patch, err := command.Output()
	if err != nil {
		return fmt.Errorf("create Reviewer snapshot patch: %w", err)
	}
	apply := exec.Command("git", "-C", dispatch.Instruction.Worktree, "apply", "--binary")
	apply.Stdin = bytes.NewReader(patch)
	var stderr bytes.Buffer
	apply.Stderr = &stderr
	if err := apply.Run(); err != nil {
		return fmt.Errorf("apply Reviewer snapshot patch: %w: %s", err, strings.TrimSpace(stderr.String()))
	}
	tree, files, _, err := captureWorktreeTree(dispatch.Instruction.Worktree,
		dispatch.Instruction.BaselineSHA, dispatch.Instruction.BaselineSHA)
	if err != nil {
		return err
	}
	if tree != dispatch.Instruction.TargetTreeSHA ||
		!sameFiles(files, dispatch.Instruction.TargetChangedFiles) {
		return fmt.Errorf("Reviewer worktree does not reproduce the approved tree snapshot")
	}
	return nil
}

func snapshotRef(dispatchID string) string {
	digest := sha256.Sum256([]byte(dispatchID))
	return "refs/taxion/snapshots/" + hex.EncodeToString(digest[:])
}

func pinSnapshot(root, dispatchID, tree string) error {
	ref := snapshotRef(dispatchID)
	zero := strings.Repeat("0", len(tree))
	if _, err := git(root, "update-ref", ref, tree, zero); err == nil {
		return nil
	}
	return verifySnapshotRef(root, dispatchID, tree)
}

func verifySnapshotRef(root, dispatchID, tree string) error {
	ref := snapshotRef(dispatchID)
	recorded, err := git(root, "rev-parse", "--verify", ref+"^{tree}")
	if err != nil {
		return fmt.Errorf("read retained snapshot ref %s: %w", ref, err)
	}
	if recorded != tree {
		return fmt.Errorf("retained snapshot ref %s points to %s, not %s", ref, recorded, tree)
	}
	return nil
}

func worktreeRoot(path string) (string, error) {
	root, err := git(path, "rev-parse", "--show-toplevel")
	if err != nil {
		return "", err
	}
	root, err = canonical(root)
	if err != nil {
		return "", fmt.Errorf("resolve snapshot worktree: %w", err)
	}
	requested, err := canonical(path)
	if err != nil || requested != root {
		return "", fmt.Errorf("snapshot path must identify the Git worktree root %s", root)
	}
	return root, nil
}

func removeCreatedWorktree(source, path string) error {
	if _, err := git(source, "worktree", "remove", "--force", path); err != nil {
		if _, statErr := os.Lstat(path); errors.Is(statErr, os.ErrNotExist) {
			return nil
		}
		return fmt.Errorf("remove incomplete Reviewer worktree: %w", err)
	}
	return nil
}
